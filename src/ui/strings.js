export const STRINGS = { en: EN, tr: TR };
export const LANGUAGES = ['en', 'tr'];

export function translate(lang, key, vars = {}) {
  const table = STRINGS[lang] ?? EN;
  let value = table[key] ?? EN[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    value = value.replaceAll(`{${k}}`, String(v));
  }
  return value;
}

export function formatTime(totalSeconds, pad = true) {
  const m = Math.floor(totalSeconds / 60);
  const s = Math.floor(totalSeconds % 60);
  return `${pad ? String(m).padStart(2, '0') : m}:${String(s).padStart(2, '0')}`;
}
